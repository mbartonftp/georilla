/* Every country Georilla knows, with capitals and alternative names.
   Facts like borders, area, population, languages and currencies come from open data in world.gen.ts;
   this file holds the names people type. Edit freely.

   c(name, iso3, continents, capitals, aliases?, wiki title?)
   A capital is a name, or [name, Wikipedia title] when the title needs disambiguating. */
import type { Capital, ContinentCode, Country } from "./types";

type CapitalSpec = string | [name: string, wiki: string];

function c(name: string, iso3: string, cont: string, caps: CapitalSpec[], aliases: string[] = [], wiki = name, partial = false): Country {
  return {
    name, iso3, wiki, aliases, partial: partial || undefined,
    cont: cont.split(",") as ContinentCode[],
    caps: caps.map((k): Capital => (typeof k === "string" ? { name: k, wiki: k, aliases: CAPITAL_ALIASES[k] || [] } : { name: k[0], wiki: k[1], aliases: CAPITAL_ALIASES[k[0]] || [] }))
  };
}

