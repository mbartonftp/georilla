/* Regenerates src/data/popularity.gen.ts: how many times each place's English Wikipedia article was read
   over the last 12 full months. That is Georilla's measure of how well known a place is, and so of rarity.
   Wikipedia's APIs aren't reachable from every machine; the "Refresh popularity" GitHub Action runs this.
   Run with: npm run data:popularity */
import { writeFileSync } from "node:fs";
import { COUNTRIES } from "../src/data/countries";
import { REGION_SETS } from "../src/data/regions";

const UA = "GeorillaDataBuild/1.0 (https://github.com/mbartonftp/georilla)";
const sleep = (ms: number) => new Promise(r => setTimeout(r, ms));
const get = async (url: string): Promise<unknown> => {
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": UA, "Api-User-Agent": UA } });
    if (res.ok) return res.json();
    if (res.status === 404) return null;
    if (attempt >= 8) throw new Error(`${res.status} ${url}`);
    // Wikimedia rate-limits bursts; back off, honouring Retry-After when given
    const wait = Number(res.headers.get("retry-after")) * 1000 || 1000 * 2 ** Math.min(attempt, 5);
    await sleep(wait);
  }
};

interface QueryResult {
  query?: {
    redirects?: { from: string; to: string }[];
    normalized?: { from: string; to: string }[];
    pages?: Record<string, { title: string; missing?: string; pageprops?: { disambiguation?: string } }>;
  };
}

async function main() {
  const titles = [...new Set([
    ...COUNTRIES.flatMap(c => [c.wiki, ...c.caps.map(k => k.wiki)]),
    ...Object.values(REGION_SETS).flat().map(r => r.wiki)
  ])].sort();
  // follow redirects to the real article, and catch disambiguation pages
  const canonical = new Map<string, string>(), problems: string[] = [];
  for (let i = 0; i < titles.length; i += 50) {
    const batch = titles.slice(i, i + 50);
    const q = (await get(`https://en.wikipedia.org/w/api.php?action=query&format=json&redirects=1&prop=pageprops&ppprop=disambiguation&titles=${encodeURIComponent(batch.join("|"))}`)) as QueryResult;
    const hop = new Map<string, string>();
    for (const m of [...(q.query?.normalized || []), ...(q.query?.redirects || [])]) hop.set(m.from, m.to);
    const pages = new Map(Object.values(q.query?.pages || {}).map(p => [p.title, p]));
    for (const t of batch) {
      let to = t; for (let n = 0; n < 3 && hop.has(to); n++) to = hop.get(to)!;
      const page = pages.get(to);
      if (!page || page.missing !== undefined) problems.push(`missing: ${t}`);
      else if (page.pageprops?.disambiguation !== undefined) problems.push(`disambiguation page: ${t}`);
      else canonical.set(t, to);
    }
  }
  const now = new Date(), end = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), 0)), start = new Date(Date.UTC(end.getUTCFullYear() - 1, end.getUTCMonth() + 1, 1));
  const ymd = (d: Date) => d.toISOString().slice(0, 10).replace(/-/g, "");
  const views: Record<string, number> = {};
  for (const [t, to] of canonical) {
    const art = encodeURIComponent(to.replace(/ /g, "_"));
    await sleep(250); // stay well under the API's rate limit
    const r = (await get(`https://wikimedia.org/api/rest_v1/metrics/pageviews/per-article/en.wikipedia/all-access/user/${art}/monthly/${ymd(start)}/${ymd(end)}`)) as { items?: { views: number }[] } | null;
    if (!r?.items?.length) { problems.push(`no pageviews: ${t}`); continue; }
    views[t] = r.items.reduce((s, x) => s + x.views, 0);
  }
  const body = Object.entries(views).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  ${JSON.stringify(k)}: ${v}`).join(",\n");
  writeFileSync(new URL("../src/data/popularity.gen.ts", import.meta.url),
    `/* Generated by scripts/fetch-popularity.ts. Do not edit by hand.
   English Wikipedia pageviews (users, all platforms), ${ymd(start)}–${ymd(end)}, via the Wikimedia REST API. */

export const VIEWS_PERIOD = ${JSON.stringify(`${start.toISOString().slice(0, 7)} to ${end.toISOString().slice(0, 7)}`)};

/** Titles that couldn't be looked up; should be empty. */
export const VIEW_PROBLEMS: string[] = ${JSON.stringify(problems, null, 2)};

export const VIEWS: Record<string, number> = {
${body}
};
`);
  console.log(`${Object.keys(views).length} of ${titles.length} titles; ${problems.length} problems`);
  problems.forEach(p => console.log("  " + p));
}

void main();
