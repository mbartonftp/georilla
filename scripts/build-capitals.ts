/* Regenerates src/data/capitals.gen.ts: where each capital city is, from Natural Earth's populated places (public domain).
   Run with: npm run data:capitals */
import { writeFileSync } from "node:fs";
import { COUNTRIES } from "../src/data/countries";

const SOURCE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_populated_places_simple.geojson";

interface Place { name: string; nameascii: string; namealt: string | null; adm0_a3: string; sov_a3: string; featurecla: string; latitude: number; longitude: number; pop_max: number }

/** Natural Earth codes that differ from ours, and spellings that differ from our capital names. */
const A3: Record<string, string> = { UNK: "KOS", SSD: "SDS", PSE: "PSX" };
const SAME: Record<string, string> = {
  "Washington, D.C.": "Washington, D.C.", "Sri Jayawardenepura Kotte": "Sri Jawewardenepura Kotte", "Naypyidaw": "Nay Pyi Taw",
  "Ngerulmud": "Melekeok", "Kyiv": "Kiev", "Astana": "Astana", "Nukuʻalofa": "Nukualofa", "Sanaa": "Sanaa", "Tarawa": "Tarawa", "Andorra la Vella": "Andorra"
};
/** Capitals Natural Earth leaves out. */
const MANUAL: Record<string, [number, number]> = { "Yaren": [166.92, -0.547] };
const fold = (s: string) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z]+/g, " ").trim();

async function main() {
  const geo = (await (await fetch(SOURCE)).json()) as { features: { properties: Place }[] };
  const places = geo.features.map(f => f.properties);
  const out: Record<string, [number, number]> = {}, problems: string[] = [];
  for (const c of COUNTRIES) for (const cap of c.caps) {
    const want = [fold(cap.name), fold(SAME[cap.name] || cap.name), ...cap.aliases.map(fold)];
    const codes = [c.iso3, A3[c.iso3]].filter(Boolean);
    const named = (p: Place) => [p.name, p.nameascii, ...(p.namealt || "").split("|")].some(n => n && want.includes(fold(n)));
    const inCountry = places.filter(p => codes.includes(p.adm0_a3) || codes.includes(p.sov_a3));
    const hit = inCountry.filter(named).sort((a, b) => +b.featurecla.startsWith("Admin-0 capital") - +a.featurecla.startsWith("Admin-0 capital") || b.pop_max - a.pop_max)[0]
      || places.filter(named).sort((a, b) => b.pop_max - a.pop_max)[0];
    if (!hit && MANUAL[cap.name]) { out[cap.name] = MANUAL[cap.name]; continue; }
    if (!hit) { problems.push(`${cap.name} (${c.name})`); continue; }
    out[cap.name] = [Math.round(hit.longitude * 1000) / 1000, Math.round(hit.latitude * 1000) / 1000];
  }
  if (problems.length) throw new Error("No location for: " + problems.join(", "));
  const body = Object.entries(out).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  ${JSON.stringify(k)}: [${v.join(", ")}]`).join(",\n");
  writeFileSync(new URL("../src/data/capitals.gen.ts", import.meta.url),
    `/* Generated by scripts/build-capitals.ts. Do not edit by hand.
   Source: Natural Earth 1:10m populated places (public domain). */
import type { LonLat } from "./types";

/** Where each capital is, as [longitude, latitude]. */
export const CAPITAL_LL: Record<string, LonLat> = {
${body}
};
`);
  console.log(`${Object.keys(out).length} capitals`);
}

void main();
