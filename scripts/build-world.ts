/* Regenerates src/data/world.gen.ts from open data:
   - mledoze/countries (ODbL): borders, area, landlocked, languages, currencies, alternative names
   - datasets/population (World Bank, CC BY 4.0): latest population per country
   Run with: npm run data:world */
import { writeFileSync } from "node:fs";
import { COUNTRIES } from "../src/data/countries";
import type { WorldFacts } from "../src/data/types";

const MLEDOZE = "https://raw.githubusercontent.com/mledoze/countries/master/countries.json";
const POPULATION = "https://raw.githubusercontent.com/datasets/population/main/data/population.csv";

/** World Bank codes that differ from mledoze's, and populations the World Bank doesn't publish. */
const WB_CODE: Record<string, string> = { UNK: "XKX" };
const POP_FALLBACK: Record<string, [pop: number, year: number, source: string]> = {
  TWN: [23_400_000, 2024, "Taiwan Ministry of the Interior"],
  VAT: [882, 2023, "Vatican City State"]
};
/** Currency changes newer than the source data. */
const CURRENCY_FIX: Record<string, string[]> = {
  BGR: ["Euro"], // joined the euro on 1 Jan 2026
  ZWE: ["United States dollar", "Zimbabwe Gold"] // the source still lists the 2009–2019 multi-currency basket
};
/** Errors in the source's land borders. */
const NOT_BORDERS: [string, string][] = [["LKA", "IND"]];

interface Mledoze {
  cca3: string; name: { common: string; native?: Record<string, { common: string; official: string }> };
  altSpellings: string[]; borders: string[]; area: number; landlocked: boolean;
  languages?: Record<string, string>; currencies?: Record<string, { name: string }>; latlng: [number, number];
}

const latin = (s: string) => /^[\p{Script=Latin}\s'’.\-]+$/u.test(s) && s.length > 2;

async function main() {
  const src = (await (await fetch(MLEDOZE)).json()) as Mledoze[];
  const csv = await (await fetch(POPULATION)).text();
  const pop = new Map<string, [number, number]>();
  for (const line of csv.trim().split(/\r?\n/).slice(1)) {
    const m = line.match(/,([A-Z]{3}),(\d{4}),([\d.]+)$/);
    if (!m) continue;
    const [, code, y, v] = m, prev = pop.get(code);
    if (!prev || +y > prev[1]) pop.set(code, [Math.round(+v), +y]);
  }
  const byIso = new Map(src.map(x => [x.cca3, x]));
  const nameOf = new Map(COUNTRIES.map(c => [c.iso3, c.name]));
  const out: Record<string, WorldFacts> = {};
  for (const c of COUNTRIES) {
    const x = byIso.get(c.iso3);
    if (!x) throw new Error(`mledoze has no ${c.iso3} (${c.name})`);
    const p = pop.get(WB_CODE[c.iso3] || c.iso3) || (POP_FALLBACK[c.iso3] && [POP_FALLBACK[c.iso3][0], POP_FALLBACK[c.iso3][1]] as [number, number]);
    if (!p) throw new Error(`no population for ${c.iso3} (${c.name})`);
    const known = new Set([c.name, ...c.aliases].map(s => s.toLowerCase()));
    const alt = [...new Set([x.name.common, ...Object.values(x.name.native || {}).flatMap(n => [n.common]), ...x.altSpellings])]
      .filter(s => latin(s) && !known.has(s.toLowerCase()));
    out[c.name] = {
      area: x.area, pop: p[0], popYear: p[1], landlocked: x.landlocked,
      borders: x.borders.filter(b => !NOT_BORDERS.some(([a, z]) => (a === c.iso3 && z === b) || (z === c.iso3 && a === b))).map(b => nameOf.get(b)).filter((b): b is string => !!b).sort(),
      languages: Object.values(x.languages || {}).sort(),
      currencies: CURRENCY_FIX[c.iso3] || Object.values(x.currencies || {}).map(k => k.name).sort(),
      alt, latlng: x.latlng
    };
  }
  const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(",\n");
  writeFileSync(new URL("../src/data/world.gen.ts", import.meta.url),
    `/* Generated by scripts/build-world.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
   Sources: mledoze/countries (ODbL 1.0), World Bank population via datasets/population (CC BY 4.0). */
import type { WorldFacts } from "./types";

export const WORLD: Record<string, WorldFacts> = {
${body}
};
`);
  console.log(`wrote ${Object.keys(out).length} countries`);
}

void main();
